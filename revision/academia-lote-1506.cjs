const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

const root = path.join(__dirname, '..');
const bankPath = path.join(root, 'preguntas_preparatic.json');
const bank = JSON.parse(fs.readFileSync(bankPath, 'utf8'));
const logPath = path.join(__dirname, 'cambios-lote-1506.json');
const log = JSON.parse(fs.readFileSync(logPath, 'utf8'));
const docs = {
  7831: ['https://drive.google.com/file/d/1-6ZS4MZmc7BjkT6tCk_LmWAgB3pIzZE3/view?usp=drivesdk', 'ITIC Academy, bloque 27 Sistemas Operativos, versión 2026', 'El material reproduce el epígrafe oficial A1-59 de fundamentos de sistemas operativos, donde se encuadra paginación y reemplazo de páginas; la definición exacta de OPT se contrasta con la fuente universitaria citada en la revisión.'],
  7832: ['https://drive.google.com/file/d/12Yp-woyL0LxoCD7MZhhQgd6Yf2UIVggH/view?usp=drivesdk', 'ITIC Academy, bloque 42 Redes, actualización 2026', 'El bloque incluye telecomunicaciones, espectro/medios de transmisión y sistemas inalámbricos (A1-108); el glosario de la Comisión Europea aporta la definición específica de dividendo digital.'],
  7833: ['https://drive.google.com/file/d/1-6ZS4MZmc7BjkT6tCk_LmWAgB3pIzZE3/view?usp=drivesdk', 'ITIC Academy, bloque 27 Sistemas Operativos, versión 2026', 'El material cubre los fundamentos del sistema operativo y la gestión del procesador bajo A1-59; la equivalencia quantum/time slice se contrasta con el manual universitario de sistemas operativos citado.'],
  7834: ['https://drive.google.com/file/d/1skUPcsGKh1eClZx6ixj2anHUVzEqy9qm/view?usp=drivesdk', 'ITIC Academy, bloque 30 Tecnologías de Sistemas de la Información, versión 2026', 'Incluye expresamente el epígrafe A1-77, HTML/CSS/XML y compatibilidad con estándares. Las condiciones formales de documento bien formado y válido se cotejan con la Recomendación XML 1.0 del W3C.'],
  7835: ['https://drive.google.com/file/d/1hPYYrCoVBKhiEgMaqVBi5mpdUEm4_vV5/view?usp=drivesdk', 'ITIC Academy, Tema 093 MÉTRICA v3', 'El material identifica al Especialista en Comunicaciones dentro del perfil Consultor y recoge su asesoramiento especializado sobre requisitos; se contrasta con el manual original de Gestión de Proyectos de MÉTRICA v3.']
};
const official = new Set(JSON.parse(fs.readFileSync(path.join(__dirname, 'temario-oficial.json'), 'utf8')).programas.flatMap(p => p.temas.map(t => t.id)));
const convocation = {
  A1: 'https://www.boe.es/diario_boe/txt.php?id=BOE-A-2025-25938',
  A2: 'https://www.boe.es/diario_boe/txt.php?id=BOE-A-2025-26262'
};
assert.equal(log.cambios.length, 5);
for (const c of log.cambios) {
  const q = bank.preguntas.find(x => x.id === c.id);
  assert.ok(q?.revision, `Falta revisión ${c.id}`);
  for (const id of [...q.clasificacion.A1, ...q.clasificacion.A2]) assert.ok(official.has(id), `Tema no oficial ${id}`);
  const [url, title, detail] = docs[c.id];
  q.revision.fuentes = q.revision.fuentes.filter(x => !x.referencia.startsWith('Cotejo curricular:') && !x.referencia.startsWith('Convocatoria oficial A1 BOE-') && !x.referencia.startsWith('Convocatoria oficial A2 BOE-'));
  q.revision.fuentes.push(
    { url, referencia: `Cotejo curricular: ${title}. ${detail}` },
    { url: convocation.A1, referencia: `Convocatoria oficial A1 BOE-A-2025-25938; epígrafe(s): ${q.clasificacion.A1.join(', ')}.` },
    { url: convocation.A2, referencia: `Convocatoria oficial A2 BOE-A-2025-26262; epígrafe(s): ${q.clasificacion.A2.join(', ')}.` }
  );
  q.revision.observaciones = `${q.revision.observaciones.split(' Cotejo curricular:')[0]} Cotejo curricular: ${title}. ${detail}`;
  q.comentarios = `${q.comentarios.split(' Cotejo curricular:')[0]} Cotejo curricular: ${title}. ${detail}`.trim();
  q.clasificacion.bloque_academia = title.replace('ITIC Academy, ', '');
  q.clasificacion.nota = `Cotejo curricular: ${detail}`;
  c.actualizada = structuredClone(q);
}
fs.writeFileSync(logPath, JSON.stringify(log, null, 2) + '\n');
fs.writeFileSync(bankPath, JSON.stringify(bank, null, 2) + '\n');
console.log('Cotejo curricular en Drive y convocatorias A1/A2 incorporado para lote 1506.');
