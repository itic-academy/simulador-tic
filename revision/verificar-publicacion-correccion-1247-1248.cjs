const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const file = path.join(__dirname, 'README.md');
let text = fs.readFileSync(file, 'utf8');
const proof = 'Publicación verificada: contenido corregido en el commit `eb63f37` (`eb63f376fee95d6323b52febded47dd61de1f33c`); [workflow Deploy GitHub Pages 43530394050](https://github.com/itic-academy/simulador-tic/actions/runs/43530394050) finalizado con estado **Success** e incluye ese commit. GitHub Pages sirvió con HTTP 200 y sin caché el banco, README, los registros de los lotes 1247/1248, `correcciones-ediciones-lotes-1247-1248.json` e `inventario.json`. Se cotejaron en el banco público las claves y reformulaciones de los ocho IDs corregidos: 6556=A, 6557=A, 6558=D, 6559=D, 6561=A, 6562=D, 6563=A y 6565=C. El inventario publicado confirma 6.560 examinadas; 6.446 verificadas (1.277 vigentes, 4.703 corregidas y 466 históricas); 114 pendientes (45 de fuente y 69 de ambigüedad) y 5.563 sin revisar; errores estructurales: 0.';
const correctionStart = text.indexOf('## Corrección técnica de los lotes 1247–1248');
assert.ok(correctionStart >= 0, 'Falta nota de corrección');
const latestStart = text.indexOf('## Lote 1248 —', correctionStart);
assert.ok(latestStart > correctionStart, 'Falta sección de lote 1248');
let correction = text.slice(correctionStart, latestStart);
correction = correction.replace('La evidencia de la corrección se documentará tras el nuevo despliegue.', proof);
assert.ok(!correction.includes('se documentará tras'), 'Falta reemplazar evidencia pendiente');
text = text.slice(0, correctionStart) + correction + text.slice(latestStart);
const start = text.indexOf('## Lote 1248 —', correctionStart);
const end = text.indexOf('## Lote 1247 —', start);
assert.ok(end > start, 'No se encuentra el final del lote 1248');
let section = text.slice(start, end);
section = section.replace(/Publicación verificada: commit de datos `a39b608`[\s\S]*?sin revisar individualmente\./, proof);
section = section.replace('Pendiente verificar la publicación del lote.', proof);
assert.ok(section.includes('43530394050'), 'La publicación de lote 1248 no quedó acreditada');
text = text.slice(0, start) + section + text.slice(end);
fs.writeFileSync(file, text);
console.log('README: evidencia del contenido corregido y publicado añadida para los lotes 1247–1248.');
